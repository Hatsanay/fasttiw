// สระอำ (ำ) ทำให้ตัวอักษร "ท้ายข้อความ" หายไปจาก PDF — ต้องแปลงก่อนส่งให้ @react-pdf/renderer
//
// อาการ: ข้อความไทยใน PDF ถูกตัดท้ายทิ้ง โดยจำนวนตัวที่หาย = จำนวนสระอำในข้อความนั้นเป๊ะๆ
// (วัดจริงแล้ว: มี ำ 1 ตัว → หายท้าย 1 ตัว, มี 6 ตัว → หายท้าย 6 ตัว) เช่นบรรทัด
// "✓ คำตอบที่ถูกต้อง" มี ำ 1 ตัว จึงกลายเป็น "✓ คำตอบที่ถูกต้อ" หายตัว ง ไปทุกข้อ
//
// สาเหตุ: fontkit แตก ำ (U+0E33) หนึ่งตัวอักษรออกเป็นสอง glyph เสมอ คือ นิคหิต (U+0E4D กว้าง 0)
// + สระอา (U+0E32) ตามหลักการเรียงพิมพ์ไทยที่ถูกต้อง แต่ @react-pdf/textkit คิดตำแหน่งตัดบรรทัดจาก
// "ลำดับตัวอักษร" ขณะที่ความกว้างมาจาก "ลำดับ glyph" — พอสองฝั่งเหลื่อมกัน ตัวท้ายจึงถูกตัดทิ้ง
//
// ทางแก้: เขียน ำ เป็น นิคหิต+สระอา ตั้งแต่ต้น (1 ตัวอักษร = 1 glyph) จำนวนตัวอักษรกับ glyph เลยตรงกัน
// พอดี ไม่มีอะไรหาย และ **หน้าตาบนกระดาษไม่เปลี่ยนเลย** เพราะ fontkit ก็แตกเป็นสอง glyph นี้อยู่แล้ว
// (ตรวจแล้วว่าได้ glyph id + ความกว้างเท่ากันทุกตัว)
//
// ผลข้างเคียงเดียว: ตอน copy ข้อความออกจาก PDF จะได้ นิคหิต+สระอา แทน ำ ซึ่งเป็นพฤติกรรมเดิมอยู่แล้ว
// ก่อนแก้ (ตาราง ToUnicode ในไฟล์ PDF แยกเป็นสอง glyph มาตั้งแต่แรก) จึงไม่ได้แย่ลงจากเดิม
const SARA_AM = "\u0E33";
const NIKHAHIT_SARA_AA = "\u0E4D\u0E32";

/** แปลงข้อความไทยให้ปลอดภัยก่อนวาดลง PDF — ใช้กับทุก <Text> ที่มีโอกาสมีสระอำ */
export function toPdfThai<T extends string | null | undefined>(value: T): T {
    return (typeof value === "string" ? value.replaceAll(SARA_AM, NIKHAHIT_SARA_AA) : value) as T;
}
